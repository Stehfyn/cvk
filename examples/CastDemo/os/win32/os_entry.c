/**
 * \par Details:
 *  The platform-neutral application body returns a status. No CRT initialization
 *  or shutdown routine participates in this entry path.
 */
void WinMainStartup(void)
{
    uint32_t status;

    status = OS_Application_Main();
    OS_Process_Exit(status);
}
