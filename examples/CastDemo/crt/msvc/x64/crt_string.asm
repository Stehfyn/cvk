;*************************************************************************************************
; Details: RCX and RDX are valid terminated strings, R8 is the maximum byte count.
;          RAX returns the difference of the first unequal unsigned bytes.
CRT_String_CompareCore PROC
    xor     eax, eax
    test    r8, r8
    jz      string_done

string_next:
    movzx   eax, byte ptr [rcx]
    movzx   r9d, byte ptr [rdx]
    sub     eax, r9d
    jne     string_done
    test    r9d, r9d
    jz      string_done
    inc     rcx
    inc     rdx
    dec     r8
    jnz     string_next
    xor     eax, eax

string_done:
    ret
CRT_String_CompareCore ENDP

END
